def steps_html(progress):
    completed = progress["completed_through"]
    results = progress.get("results", {})
    return "\n".join(
        f'<section class="step" id="step-{number}"><h3>Step {number} — {esc(title)} '
        f'<span class="badge {"complete" if int(number) <= completed else "incomplete"}">'
        f'{"observed" if int(number) <= completed else "incomplete"}</span></h3>'
        f'<p>{esc(results.get(number, description))}</p></section>'
        for number, title, description in STEPS
    )


def render(week2, week3):
    progress = json.loads(PROGRESS_PATH.read_text(encoding="utf-8"))
    completed = progress["completed_through"]
    evidence = "\n".join(
        f'<h3>{esc(title)}</h3><p class="file">week4/evidence/{esc(filename)}</p>'
        f'<pre>{esc((EVIDENCE_PATH.parent / filename).read_text(encoding="utf-8").rstrip())}</pre>'
        for title, filename, step in EVIDENCE
        if step is None or step <= completed
    )
    status = "no experiments completed" if completed < 0 else f"Steps 0–{completed} completed"
    return PAGE.format(
        week2=week2,
        week3=week3,
        today=datetime.date.today().isoformat(),
        status=status,
        steps=steps_html(progress),
        evidence=evidence,
        reflections=REFLECTIONS if completed == 6 else "",
    )


def main():
    outputs = [
        (ROOT / "week4" / "index.html", "../docs/", "../docs/week3/"),
        (ROOT / "docs" / "week4" / "index.html", "../", "../week3/"),
    ]
    for path, week2, week3 in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(week2, week3), encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
